/**
 * "Foundry" — the first original Aerocade arena. 48×27 tiles.
 * A symmetric industrial hall: high side ledges, a raised center block,
 * mid-air platforms for jetpack routes, and a floor split by two pits that
 * drop into a bottom corridor. Original layout, drawn for this project.
 *
 * Eight weapon pads ('W') sit on platform tops, spread across all three
 * height bands so no single position controls the arsenal — contesting the
 * center pads costs altitude, and the bottom pair is the safest but slowest
 * to reach. Each pad rolls a random weapon on respawn (systems/pickups.ts).
 */
